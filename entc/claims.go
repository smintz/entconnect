package entc

import (
	"fmt"
	"io"
	"sort"
	"strings"
)

// Claim is one row of the deterministic, sorted claims report INT-05
// requires: a descriptor-set procedure and its claimant — "crud:<op>" for
// a CreateRPC/GetRPC/ListRPC/UpdateRPC/DeleteRPC binding, "manual" for a
// Manual binding, or "unclaimed" for a procedure no schema's Bindings
// names at all.
type Claim struct {
	Procedure string
	Claimant  string
}

// BuildClaims labels every procedure in all (AllProcedures' sorted,
// complete descriptor-set enumeration — D-07/D-20, including RPCs no
// schema references, the property Phase 5's DRIFT-01 needs) with its
// claimant, from bindings (schema type name -> that schema's declared
// Bindings.Bindings, unresolved). BuildClaims never touches descriptor
// resolution: a stale or malformed procedure string a schema names simply
// never matches an entry in all and is silently absent from the report,
// exactly like any other procedure no schema names.
//
// The returned slice is always sorted by procedure (D-20: never build
// ordered output by ranging a map) — BuildClaims walks bindings' schema
// names in sorted order to build an intermediate claimant index, then
// walks all (already sorted) to produce the final claim list, so its
// output never depends on map iteration order or the order callers pass
// bindings in. Callers (entc/extension.go's Generate) call BuildClaims
// only after checkConflicts has already returned zero failures, so a
// procedure claimed by two schemas is never reachable here — but
// BuildClaims defends anyway (first claimant by sorted schema name wins)
// rather than panicking, so it stays safe to call standalone in tests.
func BuildClaims(all []string, bindings map[string][]Binding) []Claim {
	schemaNames := make([]string, 0, len(bindings))
	for name := range bindings {
		schemaNames = append(schemaNames, name)
	}
	sort.Strings(schemaNames)

	claimantByProcedure := make(map[string]string, len(all))
	for _, name := range schemaNames {
		for _, b := range bindings[name] {
			if _, exists := claimantByProcedure[b.Procedure]; exists {
				continue
			}
			claimant := "manual"
			if b.Op != OpManual {
				claimant = "crud:" + string(b.Op)
			}
			claimantByProcedure[b.Procedure] = claimant
		}
	}

	claims := make([]Claim, 0, len(all))
	for _, proc := range all {
		claimant, ok := claimantByProcedure[proc]
		if !ok {
			claimant = "unclaimed"
		}
		claims = append(claims, Claim{Procedure: proc, Claimant: claimant})
	}
	sort.Slice(claims, func(i, j int) bool { return claims[i].Procedure < claims[j].Procedure })
	return claims
}

// WriteClaimsReport writes one line per claim ("<procedure> <claimant>",
// tab-free, greppable) to w, preceded by a generated-file header line and
// terminating in a single trailing newline so the file diffs cleanly
// (D-07/D-20). Writing zero claims still produces a valid, header-only
// file — the empty-descriptor-set case is a visible, diffable state, not
// an absent file.
func WriteClaimsReport(w io.Writer, claims []Claim) error {
	if _, err := io.WriteString(w, "# Code generated by entconnect. DO NOT EDIT.\n"); err != nil {
		return err
	}
	for _, c := range claims {
		if _, err := fmt.Fprintf(w, "%s %s\n", c.Procedure, c.Claimant); err != nil {
			return err
		}
	}
	return nil
}

// checkConflicts detects D-05's two build-fatal conflict shapes across
// every schema's declared bindings (bindings maps schema type name ->
// that schema's declared Bindings.Bindings, exactly as BuildClaims takes
// it), collected in one pass (D-05/D-09) — never first-offense-wins:
//
//   - a procedure claimed by two or more schemas.
//   - a schema declaring the same Op twice, against two different
//     procedures (a schema naming one procedure twice for the same Op
//     would also trip the first case, so this case is reachable only via
//     genuinely distinct procedures).
//
// Every failure names every offender (D-04's self-sufficient-first-line
// discipline), and the returned slice's order is deterministic regardless
// of bindings' own map iteration order — every intermediate index below is
// walked via sorted keys.
func checkConflicts(bindings map[string][]Binding) []failure {
	var failures []failure

	schemaNames := make([]string, 0, len(bindings))
	for name := range bindings {
		schemaNames = append(schemaNames, name)
	}
	sort.Strings(schemaNames)

	// Procedure -> claiming schema names, across every schema.
	claimants := map[string][]string{}
	for _, name := range schemaNames {
		for _, b := range bindings[name] {
			claimants[b.Procedure] = append(claimants[b.Procedure], name)
		}
	}
	procs := make([]string, 0, len(claimants))
	for p := range claimants {
		procs = append(procs, p)
	}
	sort.Strings(procs)
	for _, p := range procs {
		names := claimants[p]
		if len(names) < 2 {
			continue
		}
		sorted := append([]string(nil), names...)
		sort.Strings(sorted)
		failures = append(failures, failure{
			schemaName: sorted[0], op: "", sortKey: p,
			rule:        "duplicate-claim",
			description: fmt.Sprintf("procedure %q is claimed by %d schemas: %s", p, len(sorted), strings.Join(sorted, ", ")),
			remedy:      "remove the duplicate binding — a procedure may be claimed by exactly one schema (D-05)",
		})
	}

	// Schema -> Op -> claimed procedures, one schema at a time.
	for _, name := range schemaNames {
		opProcs := map[Op][]string{}
		for _, b := range bindings[name] {
			opProcs[b.Op] = append(opProcs[b.Op], b.Procedure)
		}
		ops := make([]string, 0, len(opProcs))
		for op := range opProcs {
			ops = append(ops, string(op))
		}
		sort.Strings(ops)
		for _, opStr := range ops {
			op := Op(opStr)
			ps := opProcs[op]
			if len(ps) < 2 {
				continue
			}
			sorted := append([]string(nil), ps...)
			sort.Strings(sorted)
			failures = append(failures, failure{
				schemaName: name, op: opStr, sortKey: name + "." + opStr,
				rule:        "duplicate-op",
				description: fmt.Sprintf("schema %q declares %s twice: %s", name, opStr, strings.Join(sorted, ", ")),
				remedy:      "a schema may declare each Op at most once (D-05)",
			})
		}
	}

	return failures
}
